-- EmbossMak3r — parametric business-card embosser (rollers + body).
-- Same RLS shape as the badgemaker tables: any authenticated user, full access.

create table embosser_models (
  id bigint generated by default as identity primary key,
  name text not null,
  archived boolean not null default false,

  -- Roller. wrap_mm is the design length around the roller; the diameter
  -- follows from it (dia = wrap / pi), which is why a business-card design
  -- needs a fat roller — one card length has to fit in one revolution.
  wrap_mm numeric not null default 85.6,
  width_mm numeric not null default 54,
  repeat_count integer not null default 1,
  emboss_mm numeric not null default 0.6,
  paper_mm numeric not null default 0.3,
  clearance_mm numeric not null default 0.15,

  -- Drive + body
  axle_mm numeric not null default 5,
  gear_teeth integer not null default 18,
  gear_mm numeric not null default 4,
  plate_mm numeric not null default 4,
  post_mm numeric not null default 6,
  knob_mm numeric not null default 26,
  nip_mm numeric not null default 0.4,
  margin_mm numeric not null default 7,

  -- Viewport
  def_rot_x numeric not null default -0.4,
  def_rot_y numeric not null default 0.2,
  def_zoom numeric not null default 1,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- One row per thing on the roller surface. `content` holds the text, the SVG
-- source, or an image data URL — a logo is tens of KB, which is well inside
-- what a text column wants to carry. Move images to Storage if anyone starts
-- pasting photographs in.
create table embosser_elements (
  id bigint generated by default as identity primary key,
  model_id bigint not null references embosser_models(id) on delete cascade,
  el_order integer not null default 0,
  kind text not null default 'text',          -- text | svg | image | rect | circle
  name text not null default 'Element',
  content text not null default '',
  font_id bigint references badgemaker_fonts(id),
  font_size numeric not null default 10,
  pos_u numeric not null default 0,           -- mm around the roller
  pos_v numeric not null default 0,           -- mm along the roller
  size_w numeric not null default 20,
  size_h numeric not null default 20,
  rotation numeric not null default 0,        -- degrees
  outline_mm numeric not null default 0,      -- grow (+) / shrink (-) the outline
  threshold integer not null default 128,     -- image trace cutoff, 0-255
  invert boolean not null default false,
  visible boolean not null default true,
  created_at timestamptz not null default now()
);

create index embosser_elements_model_idx on embosser_elements(model_id);

alter table embosser_models enable row level security;
alter table embosser_elements enable row level security;

create policy "authenticated full access" on embosser_models
  for all to authenticated using (true) with check (true);
create policy "authenticated full access" on embosser_elements
  for all to authenticated using (true) with check (true);
