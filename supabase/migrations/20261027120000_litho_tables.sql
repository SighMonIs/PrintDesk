-- LithoMak3r — lithophane baubles.
-- Same RLS shape as the badgemaker and embosser tables: any authenticated
-- user, full access.

create table litho_models (
  id bigint generated by default as identity primary key,
  name text not null,
  archived boolean not null default false,

  -- The shell. Wall thickness runs between thin_mm (where the photo is
  -- brightest, so the most light gets through) and thick_mm.
  dia_mm numeric not null default 60,
  top_hole_deg numeric not null default 14,     -- half-angle, the hanger hole
  bot_hole_deg numeric not null default 16,     -- half-angle, prints on this rim
  thin_mm numeric not null default 0.7,
  thick_mm numeric not null default 2.6,

  -- Layout. Photos take equal panels around the equator; repeat_count tiles
  -- the set so a single photo need not stretch over the full 360°.
  centre_deg numeric not null default 90,       -- latitude the panels sit on
  repeat_count integer not null default 1,
  relief_side text not null default 'inside',   -- inside | outside
  detail text not null default 'normal',        -- draft | normal | fine

  hanger boolean not null default true,
  hanger_mm numeric not null default 3.6,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- One row per photo. data_url holds the downsampled image (640 px on its long
-- edge, which is all the geometry ever samples) as a JPEG data URL — roughly
-- 80 KB of base64 each.
--
-- ponytail: photos in a text column, move to Supabase Storage if a few
-- hundred designs start to weigh on the database.
create table litho_photos (
  id bigint generated by default as identity primary key,
  model_id bigint not null references litho_models(id) on delete cascade,
  photo_order integer not null default 0,
  name text not null default 'Photo',
  data_url text not null default '',
  invert boolean not null default false,
  bright numeric not null default 0,            -- -0.4 … 0.4
  contrast numeric not null default 1,          --  0.4 … 2.2
  created_at timestamptz not null default now()
);

create index litho_photos_model_idx on litho_photos(model_id);

alter table litho_models enable row level security;
alter table litho_photos enable row level security;

create policy "authenticated full access" on litho_models
  for all to authenticated using (true) with check (true);
create policy "authenticated full access" on litho_photos
  for all to authenticated using (true) with check (true);
